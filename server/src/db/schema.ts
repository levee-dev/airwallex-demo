const createdAt = () => timestamp('created_at', { withTimezone: true }).notNull().defaultNow();
const at = (name: string) => timestamp(name, { withTimezone: true });

/** The operator's platform credentials, written once by `acme setup`. Secrets are AES-256-GCM envelopes. */
export const platformConfig = pgTable(
  'platform_config',
  {
    id: integer('id').primaryKey().default(1),
    leveePlatformId: text('levee_platform_id').notNull(),
    leveeTenantId: text('levee_tenant_id').notNull(),
    leveePlatformKey: text('levee_platform_key').notNull(),
    leveePlatformKeyLast4: text('levee_platform_key_last4').notNull(),
    airwallexClientId: text('airwallex_client_id').notNull(),
    airwallexApiKey: text('airwallex_api_key').notNull(),
    airwallexApiKeyLast4: text('airwallex_api_key_last4').notNull(),
    webhookSecret: text('webhook_secret').notNull(),
    webhookSecretLast4: text('webhook_secret_last4').notNull(),
    /** The passkey RP ID setup set on the Levee tenant, shown by `acme status`. */
    passkeyRpId: text('passkey_rp_id'),
    /** Web Push (VAPID) key pair, generated by `acme setup`. The public key is not a secret. */
    vapidPublicKey: text('vapid_public_key'),
    vapidPrivateKey: text('vapid_private_key'),
    verifiedAt: at('verified_at').notNull(),
    lastWebhookAt: at('last_webhook_at'),
    /** The endpoint `npm run dev` registered with Levee, and its encrypted signing secret. */
    webhookEndpointId: text('webhook_endpoint_id'),
    webhookEndpointUrl: text('webhook_endpoint_url'),
    webhookEndpointSecret: text('webhook_endpoint_secret'),
    webhookEndpointSecretLast4: text('webhook_endpoint_secret_last4'),
    webhookEndpointRegisteredAt: at('webhook_endpoint_registered_at'),
  },
  (table) => [check('platform_config_singleton', sql`${table.id} = 1`)],
);

export const users = pgTable('users', {
  id: text('id').primaryKey(),
  email: text('email').notNull().unique(),
  passwordHash: text('password_hash').notNull(),
  displayName: text('display_name').notNull(),
  /** The end-user reference Acme sends to Levee as `x-levee-end-user`. */
  externalRef: text('external_ref').notNull().unique(),
  approverId: text('approver_id').unique(),
  /** The end user's own Airwallex connected account. */
  connectedAccountId: text('connected_account_id').unique(),
  connectedAccountStatus: text('connected_account_status'),
  /** When Levee accepted the ACTIVE account as the approver's issuer account. */
  accountLinkedAt: at('account_linked_at'),
  /** Why background account provisioning last gave up; null while it is opening or once ready. */
  accountError: text('account_error'),
  createdAt: createdAt(),
});

/** A browser's Web Push subscription, so approvals can reach the person's phone. */
export const pushSubscriptions = pgTable(
  'push_subscriptions',
  {
    id: text('id').primaryKey(),
    userId: text('end_user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    endpoint: text('endpoint').notNull().unique(),
    keys: jsonb('keys').$type<{ p256dh: string; auth: string }>().notNull(),
    userAgent: text('user_agent'),
    createdAt: createdAt(),
  },
  (table) => [index('push_subscriptions_user_idx').on(table.userId)],
);

