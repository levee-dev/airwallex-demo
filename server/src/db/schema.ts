export type WebhookEventStatus = 'pending' | 'applying' | 'processed' | 'ignored';

/**
 * Every verified Levee delivery, deduplicated by event id. A `pending` event names a person Acme
 * knows but a record Acme has not written yet; it is replayed once that record exists. `applying`
 * is a short claim so concurrent deliveries never apply the same event twice.
 */
export const webhookEvents = pgTable(
  'webhook_events',
  {
    eventId: text('event_id').primaryKey(),
    type: text('type').notNull(),
    payload: jsonb('payload').$type<WebhookEnvelope>().notNull(),
    status: text('status').$type<WebhookEventStatus>().notNull(),
    claimedAt: at('claimed_at'),
    receivedAt: at('received_at').notNull().defaultNow(),
    processedAt: at('processed_at'),
  },
  (table) => [index('webhook_events_status_idx').on(table.status, table.receivedAt)],
);

export interface WebhookEnvelope {
  readonly event_id: string;
  readonly type: string;
  readonly created_at: string;
  readonly tenant_id: string;
  readonly data: Record<string, unknown>;
}

