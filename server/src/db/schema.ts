export type ApprovalKind = 'mandate' | 'step_up' | 'resume';
export type ApprovalStatus =
  'pending' | 'deciding' | 'approved' | 'declined' | 'denied' | 'allowed_once' | 'allowed_from_now_on' | 'expired';

/**
 * Something only the person can decide, reached through a single-use approval link. The token is a
 * bearer capability for viewing and starting a passkey ceremony: it is looked up by hash and kept
 * encrypted so the same link can be shown again while the approval is open.
 */
export const approvals = pgTable(
  'approvals',
  {
    id: text('id').primaryKey(),
    userId: text('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    agentId: text('agent_id')
      .notNull()
      .references(() => agents.id, { onDelete: 'cascade' }),
    mandateId: text('mandate_id')
      .notNull()
      .references(() => mandates.id, { onDelete: 'cascade' }),
    kind: text('kind').$type<ApprovalKind>().notNull(),
    /** `mandate@version` for a mandate or resume approval, the challenge id for a step-up. */
    target: text('target').notNull(),
    version: integer('version'),
    challengeId: text('challenge_id'),
    status: text('status').$type<ApprovalStatus>().notNull().default('pending'),
    title: text('title').notNull(),
    shortTitle: text('short_title').notNull(),
    intentQuote: text('intent_quote'),
    merchantName: text('merchant_name'),
    merchantCategory: text('merchant_category'),
    amountMinor: integer('amount_minor'),
    currency: text('currency'),
    budgetRemainingMinor: integer('budget_remaining_minor'),
    firstPurchase: jsonb('first_purchase').$type<FirstPurchaseFacts>(),
    tokenHash: text('token_hash').notNull().unique(),
    tokenEncrypted: text('token_encrypted').notNull(),
    expiresAt: at('expires_at').notNull(),
    decidedAt: at('decided_at'),
    createdAt: createdAt(),
  },
  (table) => [
    uniqueIndex('approvals_open_target_idx')
      .on(table.userId, table.kind, table.target)
      .where(sql`${table.status} in ('pending', 'deciding')`),
  ],
);

